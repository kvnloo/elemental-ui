// Generate GLSL ES 3.00 from shaders/elemental_surface.wgsl with naga.
//
//   node scripts/build-glsl.mjs          write src/generated/surface-glsl.ts
//   node scripts/build-glsl.mjs --check  fail if the committed file is stale
//
// The output is committed so the web package builds without a Rust toolchain;
// CI runs --check to stop the WebGL2 path drifting from the WGSL source.
// GPL-3.0-only.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const wgslPath = join(root, "shaders/elemental_surface.wgsl");
const outPath = resolve(here, "../src/generated/surface-glsl.ts");
const wgsl = readFileSync(wgslPath, "utf8");
const work = mkdtempSync(join(process.env.TMPDIR || tmpdir(), "elemental-glsl-"));

function naga(entry, file) {
	const out = join(work, file);
	// --keep-coordinate-space: draw straight into the WebGL canvas without
	// naga's FBO-oriented y flip, so the image matches WebGPU and native.
	execFileSync("naga", [wgslPath, out, "--entry-point", entry, "--profile", "es300", "--keep-coordinate-space"], {
		stdio: ["ignore", "inherit", "inherit"],
	});
	return readFileSync(out, "utf8");
}

const vertex = naga("vs_main", "surface.vert");
const fragment = naga("fs_main", "surface.frag");

// naga names texture/sampler pairs after their WGSL group and binding.
const names = { 2: "basecolor", 3: "normal", 4: "roughness" };
const samplers = {};
for (const m of fragment.matchAll(/uniform highp sampler2D (_group_0_binding_(\d+)_fs);/g)) {
	samplers[names[m[2]]] = m[1];
}
const block = fragment.match(/uniform (\w+) \{ Params/)?.[1];
if (!block || Object.keys(samplers).length !== 3) {
	throw new Error("unexpected naga GLSL layout; update build-glsl.mjs");
}

const sourceHash = createHash("sha256").update(wgsl).digest("hex");
const body = `// GENERATED by packages/web/scripts/build-glsl.mjs from shaders/elemental_surface.wgsl.
// Do not edit; rerun \`npm run glsl\`. GPL-3.0-only.
// wgsl sha256: ${sourceHash}

export const WGSL_SHA256 = ${JSON.stringify(sourceHash)};
export const UNIFORM_BLOCK = ${JSON.stringify(block)};
export const SAMPLERS = ${JSON.stringify(samplers)} as const;
export const VERTEX = ${JSON.stringify(vertex)};
export const FRAGMENT = ${JSON.stringify(fragment)};
`;

if (process.argv.includes("--check")) {
	const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
	if (current !== body) {
		console.error(`${outPath} is stale; run \`npm run glsl -w @elemental-ui/web\``);
		process.exit(1);
	}
	console.log("GLSL is up to date with the WGSL source");
} else {
	writeFileSync(outPath, body);
	console.log(`wrote ${outPath}`);
}
